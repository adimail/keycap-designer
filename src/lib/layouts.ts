import type { KeyData } from '../types'

export const DEFAULT_KEY_STYLE = {
  labelStyle: {
    fontFamily: 'Inter',
    fontSize: 8,
    color: '#ffffff',
    position: 'center',
  },
  colour: '#2a3a3e',
  layers: [],
  visible: true,
}

type KeyDef = [
  number, // width
  string, // label
  number?, // gap after
  number?, // height
]

function generateLayout(rowDefs: { y: number; keys: KeyDef[] }[]): KeyData[] {
  const keys: KeyData[] = []
  rowDefs.forEach((def, rIdx) => {
    let col = 0
    def.keys.forEach((k, kIdx) => {
      const [w, label, gap = 0, h = 1] = k
      keys.push({
        id: `key-${rIdx}-${kIdx}`,
        row: def.y,
        col: col,
        widthUnits: w,
        heightUnits: h,
        visible: true,
        label,
        labelStyle: { ...DEFAULT_KEY_STYLE.labelStyle },
        colour: DEFAULT_KEY_STYLE.colour,
        layers: [],
      })
      col += w + gap
    })
  })
  return keys
}

